_FULL = {
    "title": TITLE_GENERATION_FULL,
    "article": ARTICLE_GENERATION_FULL,
    "report": REPORT_GENERATION_FULL,
}
_LITE = {
    "title": TITLE_GENERATION_LITE,
    "article": ARTICLE_GENERATION_LITE,
    "report": REPORT_GENERATION_LITE,
}


def _pick_template_set(model_name: str) -> dict:
    """根据模型名选择模板集：1.5b 用精简版，其余（3b/7b）用完整版。"""
    name = (model_name or "").lower()
    if "1.5b" in name:
        return _LITE
    return _FULL


def classify_doc_type(llm_response: str) -> str:
    """从 Step1 的大模型回复中解析文档类型。"""
    text = llm_response
    if "技术手册" in text or "说明书" in text:
        return "技术手册"
    if "合同" in text or "协议" in text or "法律" in text:
        return "商业合同"
    if "研报" in text or "分析" in text or "市场" in text:
        return "行业研报"
    return "通用文档"


def build_writing_prompt(
    mode: str,
    product: str,
    supplement: str,
    report_type: str,
    model_name: str = "",
) -> str:
    """
    根据当前模式拼装写作提示词。
    model_name：当前使用的模型名，用于选择完整版/精简版提示词。
    mode 为报告子类型时统一走报告模板。
    """
    sup = supplement if supplement else "无"
    report_modes = {"日常汇报", "转正述职", "年度汇报"}
    tpl = _pick_template_set(model_name)

    if mode == "爆款标题生成":
        return tpl["title"].format(product=product, supplement=sup)
    if mode == "推广软文生成":
        return tpl["article"].format(product=product, supplement=sup)
    if mode in report_modes or mode == "职场战报汇报":
        hint = REPORT_HINTS.get(report_type, "")
        return tpl["report"].format(
            report_type=report_type,
            product=product,
            supplement=sup,
            report_hint=hint,
        )
    return f"{product} {supplement}"


